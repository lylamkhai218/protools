<?php
require_once __DIR__.'/production_service.php';
function production_http($action,$pdo,$user) {
    $role=$user['role']==='ADMIN'?'ADMIN':(!empty($user['workshop_role'])?$user['workshop_role']:$user['role']);
    if (!in_array($role,array('ADMIN','WAREHOUSE','CNC','ENGINEER','INSPECTOR','SUPERVISOR','ACCOUNTANT'),true)) json_response(array('ok'=>false,'error'=>'Không có quyền truy cập Sản xuất'),403);
    if ($action==='production_runtime') {
        if ($role!=='ADMIN') json_response(array('ok'=>false,'error'=>'Không có quyền'),403);
        json_response(array('ok'=>true,'php'=>PHP_VERSION,'driver'=>$pdo->getAttribute(PDO::ATTR_DRIVER_NAME),'db_version'=>$pdo->getAttribute(PDO::ATTR_SERVER_VERSION)));
    }
    $service=new ProductionService($pdo,$user);
    try {
        if ($action==='production_evidence') {
            $hash=isset($_GET['scan'])?(string)$_GET['scan']:'';
            if (!preg_match('/^[a-f0-9]{64}$/D',$hash)) throw new ProductionError('Không tìm thấy ảnh',404);
            $s=$pdo->prepare('SELECT * FROM tt_production_evidence WHERE token_hash=?');$s->execute(array($hash));$e=$s->fetch(PDO::FETCH_ASSOC);
            if (!$e || ((int)$e['actor_id']!==(int)$user['id']&&!in_array($role,array('ADMIN','WAREHOUSE','SUPERVISOR'),true))) throw new ProductionError('Không tìm thấy ảnh',404);
            if (!preg_match('/^[a-f0-9]{48}\.jpg$/D',$e['filename'])) throw new ProductionError('Không tìm thấy ảnh',404);
            $file=__DIR__.'/storage/production-evidence/'.$e['filename'];
            if (!is_file($file)||strtotime($e['created_at'])<time()-90*86400) throw new ProductionError('Ảnh đã hết thời hạn lưu',404);
            header('Content-Type: image/jpeg');header('Cache-Control: private, no-store');header('X-Content-Type-Options: nosniff');readfile($file);exit;
        }
        if ($action==='production_workbench') json_response($service->workbench(isset($_GET['before'])?max(0,(int)$_GET['before']):0,isset($_GET['wip_before'])?max(0,(int)$_GET['wip_before']):0));
        if ($action==='production_remnant_resolve') json_response($service->remnant(isset($_GET['code'])?(string)$_GET['code']:''));
        if ($action==='production_tool_resolve') json_response($service->resolve(isset($_GET['code'])?$_GET['code']:''));
        if ($action==='production_activity') {
            if ($_SERVER['REQUEST_METHOD']!=='POST') json_response(array('ok'=>false,'error'=>'Method not allowed'),405);
            if (empty($_SESSION['tt_csrf'])||empty($_SERVER['HTTP_X_CSRF_TOKEN'])||!hash_equals($_SESSION['tt_csrf'],$_SERVER['HTTP_X_CSRF_TOKEN'])) json_response(array('ok'=>false,'error'=>'CSRF không hợp lệ'),403);
            $_SESSION['tt_last_activity']=time(); json_response(array('ok'=>true));
        }
        if ($_SERVER['REQUEST_METHOD']==='POST') {
            if (!empty($user['must_change_password']) && $action!=='production_change_password') json_response(array('ok'=>false,'error'=>'Cần đổi mật khẩu ban đầu'),403);
            if (empty($_SESSION['tt_csrf'])||empty($_SERVER['HTTP_X_CSRF_TOKEN'])||!hash_equals($_SESSION['tt_csrf'],$_SERVER['HTTP_X_CSRF_TOKEN'])) json_response(array('ok'=>false,'error'=>'CSRF không hợp lệ'),403);
            $p=json_decode(file_get_contents('php://input'),true);
            if (!is_array($p)) json_response(array('ok'=>false,'error'=>'JSON không hợp lệ'),422);
            // Internal file references can only be generated by the server.
            unset($p['_evidence_filename']);
            $evidenceFile=null;
            if ($action==='production_scan_create' && !empty($p['evidence'])) {
                $encoded=(string)$p['evidence'];
                if (strlen($encoded)>700000 || strpos($encoded,'data:image/jpeg;base64,')!==0) throw new ProductionError('Ảnh tem không hợp lệ',422);
                $image=base64_decode(substr($encoded,23),true);
                $info=$image!==false?@getimagesizefromstring($image):false;
                if (!$info||$info[2]!==IMAGETYPE_JPEG||$info[0]>4096||$info[1]>4096) throw new ProductionError('Ảnh tem phải là JPEG hợp lệ',422);
                $dir=__DIR__.'/storage/production-evidence';
                if (!is_dir($dir)&&!mkdir($dir,0700,true)) throw new ProductionError('Không lưu được ảnh tem',503);
                $filename=bin2hex(openssl_random_pseudo_bytes(24)).'.jpg';$evidenceFile=$dir.'/'.$filename;
                if (file_put_contents($evidenceFile,$image,LOCK_EX)===false) throw new ProductionError('Không lưu được ảnh tem',503);
                $p['_evidence_filename']=$filename;
            }
            $key=isset($_SERVER['HTTP_IDEMPOTENCY_KEY'])?$_SERVER['HTTP_IDEMPOTENCY_KEY']:'';
            try { $result=$service->write($action,$p,$key);
                if($evidenceFile&&!empty($result['scan_token'])) {
                    $saved=$pdo->prepare('SELECT filename FROM tt_production_evidence WHERE token_hash=?');$saved->execute(array(hash('sha256',$result['scan_token'])));
                    if($saved->fetchColumn()!==basename($evidenceFile))@unlink($evidenceFile);
                }
            }
            catch(Exception $error) { if($evidenceFile)@unlink($evidenceFile);throw $error; }
            json_response($result);
        }
        // CNC staff cannot read other employees' loans via legacy unfiltered endpoints.
        if ($role==='CNC'||$role==='ENGINEER') json_response(array('ok'=>false,'error'=>'Dùng chức năng cá nhân được phân quyền'),403);
    } catch (ProductionError $e) { json_response(array('ok'=>false,'error'=>$e->getMessage()),$e->status); }
    catch (Exception $e) { error_log('Production error: '.$e->getMessage()); json_response(array('ok'=>false,'error'=>'Phân hệ chưa sẵn sàng; cần kiểm tra migration'),503); }
}
