// Detect initial language: URL ?lang=en > localStorage mp_lang > localStorage tt_vina_locale > 'vi'
const urlParams = new URLSearchParams(window.location.search);
let currentLang = urlParams.get('lang') || localStorage.getItem('mp_lang') || localStorage.getItem('tt_vina_locale') || 'vi';
if (currentLang !== 'en' && currentLang !== 'vi') currentLang = 'vi';

function t(key) {
    if (TRANSLATIONS_AUTO[currentLang] && TRANSLATIONS_AUTO[currentLang][key]) {
        return TRANSLATIONS_AUTO[currentLang][key];
    }
    return (TRANSLATIONS_AUTO['vi'] && TRANSLATIONS_AUTO['vi'][key]) || key;
}

function applyLanguage(lang) {
    currentLang = lang;
    document.documentElement.lang = lang;

    // Save preferences
    localStorage.setItem('mp_lang', lang);
    localStorage.setItem('tt_vina_locale', lang);

    // Update URL query string cleanly without page refresh
    try {
        const url = new URL(window.location);
        if (lang === 'en') {
            url.searchParams.set('lang', 'en');
        } else {
            url.searchParams.delete('lang');
        }
        window.history.replaceState({}, '', url);
    } catch (e) {}

    // Translate document title & meta tags
    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) {
        document.title = t(titleEl.getAttribute('data-i18n'));
    }

    document.querySelectorAll('meta[data-i18n]').forEach(meta => {
        const key = meta.getAttribute('data-i18n');
        const attr = meta.getAttribute('data-i18n-attr') || 'content';
        meta.setAttribute(attr, t(key));
    });

    // Translate text nodes with [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
        if (el.tagName === 'TITLE' || el.tagName === 'META') return;
        const key = el.getAttribute('data-i18n');
        const attr = el.getAttribute('data-i18n-attr');
        if (attr) {
            el.setAttribute(attr, t(key));
        } else {
            el.textContent = t(key);
        }
    });

    // Translate HTML nodes with [data-i18n-html]
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        el.innerHTML = t(key);
    });

    // Update active class on switcher buttons
    document.querySelectorAll('.lang-switch-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Update 3D Auto-rotate button label if loaded
    const autoRotateBtn = document.getElementById('autorotate-btn');
    if (autoRotateBtn) {
        autoRotateBtn.innerHTML = '<i class="fa-solid fa-rotate"></i> ' + (autoRotate ? t('sec3.btn_autorotate_on') : t('sec3.btn_autorotate_off'));
    }
}

function initLanguageSwitcher() {
    applyLanguage(currentLang);

    document.querySelectorAll('.lang-switch-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.preventDefault();
            const targetLang = btn.getAttribute('data-lang');
            if (targetLang && targetLang !== currentLang) {
                applyLanguage(targetLang);
            }
        });
    });
}

