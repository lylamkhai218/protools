let currentLang = localStorage.getItem('tt_vina_locale') || localStorage.getItem('mp_lang') || 'vi';

function t(key) {
  if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) {
    return TRANSLATIONS[currentLang][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return (TRANSLATIONS['vi'] && TRANSLATIONS['vi'][key]) || key;
}

function getLangConfig(code) {
  return SUPPORTED_LANGS.find(l => l.code === code) || SUPPORTED_LANGS[0];
}

function applyTranslations() {
  // Translate document title if it has data-i18n
  const titleEl = document.querySelector('title');
  if (titleEl && titleEl.getAttribute('data-i18n')) {
    document.title = t(titleEl.getAttribute('data-i18n'));
  }
  
  // Translate meta description if it has data-i18n
  const metaDescEl = document.querySelector('meta[name="description"]');
  if (metaDescEl && metaDescEl.getAttribute('data-i18n')) {
    metaDescEl.setAttribute('content', t(metaDescEl.getAttribute('data-i18n')));
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr');
    if (attr) {
      el.setAttribute(attr, t(key));
    } else {
      el.textContent = t(key);
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });

  document.documentElement.lang = currentLang;

  // Update dropdown display
  const cfg = getLangConfig(currentLang);
  const flagEl = document.getElementById('currentLangFlag');
  if (flagEl) flagEl.innerHTML = cfg.flag;
  const labelEl = document.getElementById('currentLangLabel');
  if (labelEl) labelEl.textContent = cfg.name;

  // Update active state in desktop dropdown
  document.querySelectorAll('.lang-dropdown-item').forEach(item => {
    const isAct = item.dataset.lang === currentLang;
    item.classList.toggle('active', isAct);
    const checkEl = item.querySelector('.lang-item-check');
    if (checkEl) checkEl.style.display = isAct ? 'inline' : 'none';
  });

  // Update active state in mobile menu
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });

  // Legacy fallback buttons
  document.querySelectorAll('.lang-btn button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });

  // Update alternate link
  const altLink = document.querySelector('link[rel="alternate"]');
  if (altLink) altLink.setAttribute('hreflang', currentLang);
}

function switchLang(lang) {
  if (lang === currentLang) return;
  currentLang = lang;
  localStorage.setItem('mp_lang', lang);
  localStorage.setItem('tt_vina_locale', lang);
  applyTranslations();
  closeLangDropdown();
}

function toggleLangDropdown(e) {
  if (e) e.stopPropagation();
  const wrapper = document.getElementById('langDropdownWrapper');
  const btn = document.getElementById('langDropdownBtn');
  const menu = document.getElementById('langDropdownMenu');
  if (!wrapper || !menu) return;

  const isOpen = menu.classList.contains('show');
  if (isOpen) {
    closeLangDropdown();
  } else {
    menu.classList.add('show');
    wrapper.classList.add('active');
    if (btn) btn.setAttribute('aria-expanded', 'true');
  }
}

function closeLangDropdown() {
  const wrapper = document.getElementById('langDropdownWrapper');
  const btn = document.getElementById('langDropdownBtn');
  const menu = document.getElementById('langDropdownMenu');
  if (menu) menu.classList.remove('show');
  if (wrapper) wrapper.classList.remove('active');
  if (btn) btn.setAttribute('aria-expanded', 'false');
}

function initI18n() {
  applyTranslations();

  // Dropdown button trigger
  const btn = document.getElementById('langDropdownBtn');
  if (btn) {
    btn.addEventListener('click', toggleLangDropdown);
  }

  // Dropdown items click
  document.querySelectorAll('.lang-dropdown-item').forEach(item => {
    item.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      switchLang(item.dataset.lang);
    });
  });

  // Mobile lang buttons
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      switchLang(btn.dataset.lang);
    });
  });

  // Legacy buttons fallback
  document.querySelectorAll('.lang-btn button').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      switchLang(btn.dataset.lang);
    });
  });

  // Close dropdown when clicking outside
  document.addEventListener('click', (e) => {
    const wrapper = document.getElementById('langDropdownWrapper');
    if (wrapper && !wrapper.contains(e.target)) {
      closeLangDropdown();
    }
  });

  // Close on Escape key
  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      closeLangDropdown();
    }
  });
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
